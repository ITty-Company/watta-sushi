export const PHONE_COUNTRIES: PhoneCountry[] = RAW.map(([iso, name, dial]) => ({
  iso,
  name,
  dial,
}))

export const DEFAULT_PHONE_COUNTRY_ISO = 'UA'

export function findPhoneCountryByIso(iso: string): PhoneCountry | undefined {
  return PHONE_COUNTRIES.find((c) => c.iso === iso)
}

export function findPhoneCountryByDial(dial: string): PhoneCountry | undefined {
  const normalized = dial.replace(/\D/g, '')
  if (!normalized) return undefined
  return [...PHONE_COUNTRIES]
    .sort((a, b) => b.dial.length - a.dial.length)
    .find((c) => normalized.startsWith(c.dial) || c.dial === normalized)
}

/** Спроба розпізнати країну з повного номера (+…). */
export function matchPhoneCountryFromE164(e164: string): { country: PhoneCountry; local: string } | null {
  const digits = e164.replace(/\D/g, '')
  if (digits.length < 4) return null
  const country = findPhoneCountryByDial(digits)
  if (!country) return null
  const local = digits.slice(country.dial.length).replace(/^0+/, '')
  if (!local) return null
  return { country, local }
}
