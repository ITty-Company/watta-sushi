/** ISO → emoji flag (regional indicators). */
export function isoToFlag(iso: string): string {
  const code = iso.toUpperCase()
  if (code.length !== 2) return '🌍'
  return String.fromCodePoint(...[...code].map((c) => 127397 + c.charCodeAt(0)))
}

